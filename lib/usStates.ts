export const usStateByAbbr = (abbr: string): UsState | undefined => US_STATES.find(s => s.abbr === abbr)

/**
 * Whether a Places prediction lies in the state, from its terms
 * (e.g. ["Austin", "TX", "USA"]): the state shows up as its abbreviation or,
 * for some places, its full name. The name alone is not enough for
 * "Washington" (DC vs the state) or "New York" (city vs state), so the term
 * must sit right before "USA".
 */
export function predictionInState(terms: string[], state: UsState): boolean {
  const t = terms.map(s => s.trim())
  const usa = t.lastIndexOf('USA')
  const beforeCountry = usa > 0 ? t[usa - 1] : t[t.length - 1]
  // The state itself ("Texas, USA") is not an area within it: its results
  // would describe one point in the middle of the state
  if (t.length <= 2 && (t[0] === state.name || t[0] === state.abbr)) return false
  return beforeCountry === state.abbr || beforeCountry === state.name
}
